"""Prove the int6/int5 factor levels work in a REAL training loop, on CPU, while the GPU is busy.

WHY. `int6`/`int5` are new to the training side: `rwkv/architecture.py` `_QMAX` held only
int8/int4/int3/int2/fp32, so `card:2:int6` raised `KeyError` in `_apply_qat_scopes` and no QAT run
could train for those grids. The keys were added on 2026-11-22 together with the three ladder
candidates, and this script is the pre-flight for chain 17: if the level is still unusable, chain 17's
own 0.04-epoch smoke would fail, `qat_point` would SKIP every point and the GPU would idle at the end
of the queue.

It reuses the E1 smoke's proven shape (`e1_cpu_smoke.py`): the config is generated by
`qat_decay.py --dry-run` for the candidate itself (so it is the harness's own config, with the
harness's own 66,000-token batch cap -- a smaller cap makes `get_groups` drop users and trips
`assert FETCH_AHEAD <= len(groups)`), then only DEVICE is patched. DTYPE stays at the generator's
bfloat16 because the training forward casts the model to bf16 regardless of that field, and a
float32 batch then hits `mat1 and mat2 must have the same dtype` in `features2card`.

WHAT IT PROVES: the config parses, the `[QAT-LOWRANK]` banner reports fq=31.0 for card and note
(direct evidence the int6 qmax reached the layer configs), 3 steps run, the loss stays finite, and the
model is saved. It is NOT an accuracy result and NOT the required 0.04-epoch GPU smoke -- chain 17
still runs that on the real path.

The fused CUDA kernels are not exercised here (no CUDA extension on the CPU path). They need no check:
they compute `fminf(fmaxf(roundf(x / qmax), -qmax), qmax) * (amax / qmax)` (rwkv7_cuda.cu:468-474,
736-740), which is generic in qmax.

Usage: .venv/Scripts/python.exe scratchpad/quant_plan/corruption/int6_cpu_smoke.py [candidate]
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUN = HERE.parent                      # scratchpad/quant_plan
ROOT = HERE.parents[2]
PY = ROOT / ".venv" / "Scripts" / "python.exe"
CAND = sys.argv[1] if len(sys.argv) > 1 else "l2i6s4"
TAG = f"{CAND}cpufake"
DST = RUN / f"qat_{TAG}"
TOML = DST / "train.toml"
STEPS = 3


def toml_set(text: str, key: str, value: str) -> str:
    out, n = re.subn(rf'(?m)^{key} = .*$', f"{key} = {value}", text)
    if n != 1:
        raise SystemExit(f"expected exactly one {key} line, found {n}")
    return out


def main() -> int:
    sys.path.insert(0, str(RUN))
    import quant_sweep as qs

    env_over, comment, _ = qs.CANDIDATES[CAND]
    print(f"candidate {CAND}: {comment}")
    for k, v in env_over.items():
        print(f"   {k}={v}")

    gen = subprocess.run(
        [str(PY), "-X", "utf8", str(RUN / "qat_decay.py"), "--candidate", CAND,
         "--train-users", "1", "100",
         "--start-folder", "pretrain/rwkv/opt_iter36", "--start-name", "rwkv_iter36_558",
         "--epochs", "0.04", "--max-steps", str(STEPS), "--tag", TAG, "--dry-run"],
        cwd=str(ROOT), capture_output=True, text=True)
    print(gen.stdout.strip()[-300:])
    if gen.returncode != 0 or not TOML.exists():
        print(f"ABORT: dry-run failed rc={gen.returncode}\n{gen.stderr[-800:]}")
        return 1

    text = toml_set(TOML.read_text(encoding="utf-8"), "DEVICE", '"cpu"')
    TOML.write_text(text, encoding="utf-8")
    print(f"patched {TOML}: DEVICE=cpu (batch cap, step count and dtype are the generator's own)")

    env = dict(os.environ)
    env.update({
        "RWKV_NO_JIT": "1",
        "RWKV_WEIGHT_DECAY": "0.01",
        "RWKV_WEIGHT_DECAY_CMIX": "0.01",
        "RWKV_WEIGHT_DECAY_HEAD": "0.01",
        "RWKV_ID_FEATURES": "0",
        "RWKV_REAL_CYCLES": "0",
        "RWKV_FINAL_LAYOUT": "0",
        "RWKV_E2S_PUBLISHED": "0",
        "RWKV_MAX_STEPS": str(STEPS),
        **{k: str(v) for k, v in env_over.items()},
    })
    env.pop("RWKV_VRAM_CAP_GB", None)          # cuda-only
    print(f"running: {PY} -u -m rwkv.train_rwkv --config {TOML}")
    with (DST / "train.log").open("w", encoding="utf-8", errors="replace") as fh:
        p = subprocess.run([str(PY), "-u", "-m", "rwkv.train_rwkv", "--config", str(TOML)],
                           cwd=str(ROOT), env=env, stdout=fh, stderr=subprocess.STDOUT)

    log = (DST / "train.log").read_text(encoding="utf-8", errors="replace")
    lowrank_lines = [ln for ln in log.splitlines() if ln.startswith("[QAT-LOWRANK]")]
    nan_lines = [ln for ln in log.splitlines() if "Nan from RWKV-7" in ln]
    got31 = any("fq=31.0" in ln for ln in lowrank_lines)
    print(f"\nreturncode: {p.returncode}   MODEL SAVED.: {'MODEL SAVED.' in log}   "
          f"traceback: {'Traceback (most recent call last)' in log}")
    print(f"[QAT-LOWRANK] lines: {len(lowrank_lines)}   fq=31.0 seen: {got31}   "
          f"NaN-batch lines: {len(nan_lines)}")
    for ln in lowrank_lines[:2]:
        print("   " + ln)
    for ln in log.splitlines():
        if ln.startswith("[QAT"):
            print("   " + ln)
    ok = (p.returncode == 0 and "MODEL SAVED." in log and got31
          and "Traceback (most recent call last)" not in log and not nan_lines)
    print("\nVERDICT:", f"PASS - {CAND} trains in the real trainer at fq=31.0" if ok
          else "FAIL - see the log")
    (DST / "int6_cpu_smoke.json").write_text(json.dumps(
        {"candidate": CAND, "rc": p.returncode, "model_saved": "MODEL SAVED." in log,
         "lowrank_lines": lowrank_lines[:2], "fq31_seen": got31, "nan_lines": len(nan_lines),
         "pass": ok}, indent=1), encoding="utf-8")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
