"""Measure the state-subspace question on real states, then analyze the dump.

Runs a normal eval (get_result) over a few long-history users with the raw-state dump probe
installed and the Python per-step QAT loop forced (RWKV_QAT_FUSED=0: the pre-truncation state only
exists there). The eval's log loss is irrelevant and is not recorded; only `states_<tag>.npz` and
`state_subspace_<tag>.json` matter.

Default device is CPU so the measurement cannot compete with the training/eval GPU, and so the
states are fp32 (the faithful spectrum). The two default users are the ones the tail-energy probe
used, so the SVD curve computed here can be checked against `tail_energy_l2i8s4.json`
(card rank 2 -> 0.9938, note rank 1 -> 0.9694).

Usage:
  .venv/Scripts/python.exe scratchpad/quant_plan/corruption/measure_state_subspace.py \
      --config l2i8s4 --users 7213,7044 --tag l2i8s4 [--device cpu] [--every 4]
"""
import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
RUN = ROOT / "scratchpad" / "quant_plan"
PY = ROOT / ".venv" / "Scripts" / "python.exe"
if not PY.exists():
    PY = Path(sys.executable)

sys.path.insert(0, str(RUN))
import quant_sweep as qs  # noqa: E402

TOML = HERE / "eval_stateprobe.toml"
USERS = HERE / "users_stateprobe.json"
OUTDIR = HERE / "state_probe_out"

TEMPLATE = """# Generated by measure_state_subspace.py -- the raw-state dump probe's eval config.
FILE_AHEAD = "adw_stateprobe_{tag}"
FILE_IMM = "adwP_stateprobe_{tag}"

MODEL_PATH = "{model}"
DEVICE = "{device}"
DTYPE = "{dtype}"

DATASET_LMDB_PATH = "F:/rwkv_lmdb/test_db_5k_adaptive92"
DATASET_LMDB_SIZE = 250000000000
LABEL_FILTER_LMDB_PATH = "F:/rwkv_lmdb/label_filter_db_id_e2s"
LABEL_FILTER_LMDB_SIZE = 40000000000

RAW = false
RAW_DB_PATH = "raw/result_db"
RAW_DB_SIZE = 3_000_000_000

USER_START = 5001
USER_END = 7500
NUM_FETCH_PROCESSES = 1
USERS_FILE = "{users}"
"""

# checkpoint per recipe (the same ones the corruption check uses)
CKPT = {
    "l2i8s4": RUN / "qat_it36l2i8s4" / "qat_124.pth",
    "l3i8s4": RUN / "qat_it36l3i8s4" / "qat_124.pth",
    "l2i8": RUN / "qat_it36l2i8" / "qat_124.pth",
    "l2i8n2i8": RUN / "qat_it36l2i8n2i8" / "qat_124.pth",
    "l2i6c": RUN / "qat_it36l2i6c" / "qat_124.pth",
    "n1i8s3": RUN / "qat_it36n1i8s3" / "qat_124.pth",
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="l2i8s4", help="a quant_sweep candidate name in CKPT")
    ap.add_argument("--users", default="7213,7044")
    ap.add_argument("--tag", default="")
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--dtype", default="")
    ap.add_argument("--every", type=int, default=4, help="keep every N-th state")
    ap.add_argument("--max", type=int, default=4000, help="max states kept per key")
    ap.add_argument("--threads", type=int, default=6, help="torch/OMP threads (CPU runs)")
    ap.add_argument("--no-analyze", action="store_true")
    args = ap.parse_args()

    if args.config not in CKPT:
        raise SystemExit(f"unknown config {args.config}; known: {sorted(CKPT)}")
    ckpt = CKPT[args.config]
    if not ckpt.exists():
        raise SystemExit(f"checkpoint missing: {ckpt}")
    tag = args.tag or args.config
    dtype = args.dtype or ("float" if args.device == "cpu" else "bfloat16")

    users = [int(u) for u in args.users.split(",") if u.strip()]
    USERS.write_text(json.dumps(users), encoding="utf-8")
    TOML.write_text(TEMPLATE.format(tag=tag, model=str(ckpt).replace("\\", "\\\\"),
                                    device=args.device, dtype=dtype,
                                    users=str(USERS).replace("\\", "\\\\")), encoding="utf-8")
    OUTDIR.mkdir(parents=True, exist_ok=True)

    env = qs.base_env()
    env_extra, _comment, _bits = qs.CANDIDATES[args.config]
    env.update({k: str(v) for k, v in env_extra.items()})
    env.update({
        "RWKV_NO_JIT": "1",
        # the pre-truncation state only exists on the Python per-step loop (bit-parity twin)
        "RWKV_QAT_FUSED": "0",
        "RWKV_STATE_PROBE": "1",
        "RWKV_STATE_PROBE_DIR": str(OUTDIR),
        "RWKV_STATE_PROBE_TAG": tag,
        "RWKV_STATE_PROBE_EVERY": str(max(1, args.every)),
        "RWKV_STATE_PROBE_MAX": str(args.max),
        "RWKV_EVAL_CAST_FP32": "1" if args.device == "cpu" else "0",
        "RWKV_EXIT_HARD": "0",
        "OMP_NUM_THREADS": str(args.threads),
        "MKL_NUM_THREADS": str(args.threads),
    })
    env.pop("RWKV_FINITE_PROBE", None)

    print(f"config={args.config} ckpt={ckpt}\nusers={users} device={args.device} dtype={dtype}\n"
          f"env={env_extra}\nevery={args.every} max={args.max} threads={args.threads}\n"
          f"out={OUTDIR / f'states_{tag}.npz'}", flush=True)
    t0 = time.time()
    r = subprocess.run([str(PY), "-u", str(HERE / "state_get_result.py"), "--config", str(TOML)],
                       cwd=ROOT, env=env)
    print(f"\nrc={r.returncode} in {(time.time() - t0) / 60:.1f} min", flush=True)

    npz = OUTDIR / f"states_{tag}.npz"
    if not npz.exists():
        print(f"NO DUMP at {npz} -- the probe never observed a state (treat as INCOMPLETE)")
        return 1
    if args.no_analyze:
        return 0 if r.returncode == 0 else 1
    out = HERE / f"state_subspace_{tag}.json"
    a = subprocess.run([str(PY), "-u", str(HERE / "analyze_state_subspace.py"),
                        "--npz", str(npz), "--out", str(out)], cwd=ROOT, env=env)
    return 0 if (r.returncode == 0 and a.returncode == 0) else 1


if __name__ == "__main__":
    sys.exit(main())
