"""Measure the rank-r tail energy of REAL card/note states, to choose the E1 lambda from data.

Runs a normal eval (get_result) over a few long-history users with the tail probe installed and the
Python per-step QAT loop forced (RWKV_QAT_FUSED=0: the pre-truncation state only exists there). The
eval's own log loss is irrelevant here and is not recorded; only `tail_energy_<tag>.json` matters.

Default device is CPU so the measurement cannot compete with the training GPU (and fp32 states are
the more faithful spectrum). Two long-history users from the corruption roster are enough: the tail
energy is a property of the state distribution, and the roster was chosen for exactly that.

Usage:
  .venv/Scripts/python.exe scratchpad/quant_plan/corruption/measure_tail_energy.py \
      --config l2i8s4 --users 7213,7044 --tag l2i8s4 [--device cpu]
"""
import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
RUN = ROOT / "scratchpad" / "quant_plan"
PY = ROOT / ".venv" / "Scripts" / "python.exe"
if not PY.exists():
    PY = Path(sys.executable)

sys.path.insert(0, str(RUN))
import quant_sweep as qs  # noqa: E402

TOML = HERE / "eval_tailprobe.toml"
USERS = HERE / "users_tailprobe.json"

TEMPLATE = """# Generated by measure_tail_energy.py -- the tail-energy probe's eval config (see tail_probe.py).
FILE_AHEAD = "adw_tailprobe_{tag}"
FILE_IMM = "adwP_tailprobe_{tag}"

MODEL_PATH = "{model}"
DEVICE = "{device}"
DTYPE = "{dtype}"

DATASET_LMDB_PATH = "F:/rwkv_lmdb/test_db_5k_adaptive92"
DATASET_LMDB_SIZE = 250000000000
LABEL_FILTER_LMDB_PATH = "F:/rwkv_lmdb/label_filter_db_id_e2s"
LABEL_FILTER_LMDB_SIZE = 40000000000

RAW = false
RAW_DB_PATH = "raw/result_db"
RAW_DB_SIZE = 3_000_000_000

USER_START = 5001
USER_END = 7500
NUM_FETCH_PROCESSES = 1
USERS_FILE = "{users}"
"""

# checkpoint per recipe (the same ones the corruption check uses)
CKPT = {
    "l2i8s4": RUN / "qat_it36l2i8s4" / "qat_124.pth",
    "l3i8s4": RUN / "qat_it36l3i8s4" / "qat_124.pth",
    "l2i8": RUN / "qat_it36l2i8" / "qat_124.pth",
    "l2i8n2i8": RUN / "qat_it36l2i8n2i8" / "qat_124.pth",
    "l3i8n2i8": RUN / "qat_it36l3i8n2i8" / "qat_124.pth",
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="l2i8s4", help="a quant_sweep candidate name in CKPT")
    ap.add_argument("--users", default="7213,7044")
    ap.add_argument("--tag", default="")
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--dtype", default="")
    args = ap.parse_args()

    if args.config not in CKPT:
        raise SystemExit(f"unknown config {args.config}; known: {sorted(CKPT)}")
    ckpt = CKPT[args.config]
    if not ckpt.exists():
        raise SystemExit(f"checkpoint missing: {ckpt}")
    tag = args.tag or args.config
    dtype = args.dtype or ("float" if args.device == "cpu" else "bfloat16")

    users = [int(u) for u in args.users.split(",") if u.strip()]
    USERS.write_text(json.dumps(users), encoding="utf-8")
    # TOML basic strings interpret backslash escapes, so a Windows path must be doubled (`\U` in
    # `\Users` is a unicode escape: "Invalid hex value at line 5").
    TOML.write_text(TEMPLATE.format(tag=tag, model=str(ckpt).replace("\\", "\\\\"),
                                    device=args.device, dtype=dtype,
                                    users=str(USERS).replace("\\", "\\\\")), encoding="utf-8")
    out = HERE / f"tail_energy_{tag}.json"

    env = qs.base_env()
    env_extra, _comment, _bits = qs.CANDIDATES[args.config]
    env.update({k: str(v) for k, v in env_extra.items()})
    env.update({
        "RWKV_NO_JIT": "1",
        # the pre-truncation state only exists on the Python per-step loop (bit-parity twin)
        "RWKV_QAT_FUSED": "0",
        "RWKV_TAIL_PROBE": "1",
        "RWKV_TAIL_PROBE_OUT": str(out),
        "RWKV_EVAL_CAST_FP32": "1",
        "RWKV_EXIT_HARD": "0",
    })
    env.pop("RWKV_FINITE_PROBE", None)
    env.pop("RWKV_VRAM_CAP_GB", None)

    print(f"config={args.config} ckpt={ckpt}\nusers={users} device={args.device} dtype={dtype}\n"
          f"env={env_extra}\nout={out}", flush=True)
    t0 = time.time()
    r = subprocess.run([str(PY), "-u", str(HERE / "tail_get_result.py"), "--config", str(TOML)],
                       cwd=ROOT, env=env)
    print(f"\nrc={r.returncode} in {(time.time() - t0) / 60:.1f} min", flush=True)
    if out.exists():
        doc = json.loads(out.read_text(encoding="utf-8"))
        print(json.dumps(doc, indent=1))
    else:
        print(f"NO OUTPUT at {out} -- the probe never observed a state (treat as INCOMPLETE)")
        return 1
    return 0 if r.returncode == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
