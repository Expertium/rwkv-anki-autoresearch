"""Measure the token-shift subspace question on real shift vectors, then analyze the dump.

Runs a normal eval (get_result) over a few long-history users with the raw-shift dump probe
installed and the Python per-step QAT loop forced (RWKV_QAT_FUSED=0). The eval's log loss is
irrelevant and is not recorded; only `shifts_<tag>.npz` and `shift_subspace_<tag>.json` matter.

The shift scope is set to ONE stream per run (`RWKV_QAT_SHIFT_SCOPE=<stream>:int4`), which is what
gives the dump its stream identity: only that stream's mixers have a finite `state_shift_qmax`, so
only their forwards call `fake_quant_shift`. Two roles are recorded per layer - role 0 is the WKV
mixer's `t_xshift`, role 1 the channel mixer's `c_xshift`.

Default device is CPU so the measurement cannot compete with the training/eval GPU.

Usage:
  .venv/Scripts/python.exe scratchpad/quant_plan/corruption/measure_shift_subspace.py \
      --config l2i8s4 --stream note --users 7213,7044 --tag note_l2i8s4 [--device cpu]
"""

