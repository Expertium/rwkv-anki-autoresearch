def main():
    if not os.path.exists(os.path.join("scratchpad", "w10qat", DECAYLOG)):
        sys.exit(f"REFUSING: {DECAYLOG} does not exist")
    src = io.open(SRC_RUNNER, encoding="utf-8", newline="").read().replace("\r\n", "\n")
    a = src.index("set PYTHONUNBUFFERED=1")
    b = src.index("set RWKV_QAT_SHIFT_PQ_LEARN=1") + len("set RWKV_QAT_SHIFT_PQ_LEARN=1")
    env = src[a:b]
    # The env block must carry the WHOLE QAT stack, or the eval is not arm 2's configuration.
    for need in ("RWKV_QAT_LOWRANK_SCOPE=card:1:int4,note:1:int4", "RWKV_QAT_SHIFT_SCOPE=card:int3,note:int3",
                 "RWKV_QAT_NORM_BITS=1", "RWKV_QAT_FUSED=1", "RWKV_ID_FEATURES=1", "RWKV_REAL_CYCLES=1",
                 "RWKV_EVAL_DB=F:/rwkv_lmdb/test_db_5k_id5", "RWKV_STRIP_CMIX=user_id:0"):
        if need not in env:
            sys.exit(f"REFUSING: the copied env lacks {need}")
    if re.search(r"^\s*(if|call|echo|findstr|goto)\b", env, re.M | re.I):
        sys.exit("REFUSING: the copied env block contains control flow, not only `set` lines")

    out = HEADER.replace("__DECAYLOG__", DECAYLOG) + env + "\n" + TAIL

    # The re-point must come AFTER the verbatim env, or the verbatim START catalogs win.
    i_start = out.index("set RWKV_QAT_PQ=reference/pq_cb_wkv_ws10_b10.txt")
    i_learn = out.index("set RWKV_QAT_PQ=scratchpad/ws10/w10q_d_wkvcb_%STEPS%.txt")
    if not i_start < i_learn:
        sys.exit("REFUSING: the learned-catalog re-point does not follow the copied env")
    codes = re.findall(r"echo DONE_EXIT_(\d+) ", out)
    if len(codes) != len(set(codes)):
        sys.exit(f"REFUSING: duplicate exit codes {sorted(codes)}")
    if out.index("echo DONE_EXIT_0 ") > out.rindex("endlocal"):
        sys.exit("REFUSING: the terminal marker follows endlocal")

    io.open(OUT, "w", encoding="ascii", newline="\r\n").write(out)
    d = open(OUT, "rb").read()
    print(f"wrote {OUT}  ({d.count(b'\n')} lines, {d.count(b'\r\n')} CRLF)")
    print(f"  exit codes {sorted(int(c) for c in codes)}")
    print(f"  eval loads scratchpad/ws10/w10q_d_{{wkv,shift}}cb_{STEPS}.txt, learning off")


if __name__ == "__main__":
    main()
