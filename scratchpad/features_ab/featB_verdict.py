"""featB's verdict, written BEFORE featB reported. Tests the three predictions in featB/PREREG.md.

Do not edit this file once featB has produced numbers -- that is the entire point of it existing
early. The interval verdict worked because its analysis was fixed in advance; this is the same
instrument for the features arm.

Sign convention throughout: **positive delta = featB BETTER than featA2.**

Usage: featB_verdict.py
"""
import json
import os
import sys

CTRL, TREAT = "featA2", "featB"
# the interval pair, used to subtract the end-to-start penalty featB pays inside its bundle
IV_CTRL, IV_TREAT = "fixc", "e2sc"
SHARE_CACHE = "scratchpad/features_ab/sameday_share.json"

# measured on the fixc/e2sc pair, for reporting the features-only figure
IV_AHEAD, IV_IMM = 0.000225, 0.000400


def load(tag, mode):
    f = "result/RWKV-%s.jsonl" % tag if mode == "ahead" else "result/RWKV-P-%s.jsonl" % tag
    if not os.path.exists(f):
        return None
    out = {}
    for line in open(f):
        line = line.strip()
        if line:
            r = json.loads(line)
            out[r["user"]] = r
    return out


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def spearman(a, b):
    def ranks(v):
        order = sorted(range(len(v)), key=lambda i: v[i])
        r = [0.0] * len(v)
        for pos, i in enumerate(order):
            r[i] = float(pos)
        return r
    ra, rb = ranks(a), ranks(b)
    n = len(a)
    ma, mb = mean(ra), mean(rb)
    num = sum((ra[i] - ma) * (rb[i] - mb) for i in range(n))
    da = sum((ra[i] - ma) ** 2 for i in range(n)) ** 0.5
    db = sum((rb[i] - mb) ** 2 for i in range(n)) ** 0.5
    return num / (da * db) if da and db else float("nan")


def quartiles(keys, by, val):
    order = sorted(keys, key=lambda u: by[u])
    n = len(order)
    return [order[i * n // 4:(i + 1) * n // 4] for i in range(4)]


def main():
    print("=" * 78)
    print("featB VERDICT -- tests scratchpad/features_ab/featB/PREREG.md, written in advance")
    print("Sign convention: POSITIVE = featB BETTER than featA2")
    print("=" * 78)
    print()

    data = {}
    for tag in (CTRL, TREAT):
        for mode in ("ahead", "imm"):
            d = load(tag, mode)
            if d is None:
                print("MISSING: result jsonl for %s/%s -- featB has not reported yet." % (tag, mode))
                return 2
            data[(tag, mode)] = d

    common = sorted(set(data[(CTRL, "ahead")]) & set(data[(TREAT, "ahead")])
                    & set(data[(CTRL, "imm")]) & set(data[(TREAT, "imm")]))
    print("users compared: %d" % len(common))
    if not common:
        print("  *** no overlap -- FAILED TEST, not a pass")
        return 2

    # ---------- P3 first: it defines the subset the headline is judged on ----------
    diff_size = [u for u in common
                 if data[(CTRL, "ahead")][u].get("size") != data[(TREAT, "ahead")][u].get("size")]
    frac = 100.0 * len(diff_size) / len(common)
    matched = [u for u in common if u not in set(diff_size)]
    print()
    print("--- P3: the dataset confound (predicted 20-40% of users differ in `size`)")
    print("  users with a DIFFERENT scored review count: %d of %d (%.1f%%)"
          % (len(diff_size), len(common), frac))
    print("  -> %s" % ("as predicted" if 20.0 <= frac <= 40.0 else "OUTSIDE the predicted band"))
    print("  size-matched subset: %d users (the apples-to-apples comparison)" % len(matched))

    # ---------- P1: direction and size, on both the full set and the matched subset ----------
    print()
    print("--- P1: featB beats featA2 in BOTH modes, ahead gain in [0.0005, 0.004]")
    verdict = {}
    for label, users in (("full   ", common), ("matched", matched)):
        if not users:
            print("  %s : empty subset, skipped" % label)
            continue
        row = {}
        for mode in ("ahead", "imm"):
            c = mean([data[(CTRL, mode)][u]["metrics"]["LogLoss"] for u in users])
            t = mean([data[(TREAT, mode)][u]["metrics"]["LogLoss"] for u in users])
            row[mode] = (c, t, c - t)
        verdict[label.strip()] = row
        print("  %s n=%-5d  ahead %.6f -> %.6f  delta %+.6f   |   imm %.6f -> %.6f  delta %+.6f"
              % (label, len(users), row["ahead"][0], row["ahead"][1], row["ahead"][2],
                 row["imm"][0], row["imm"][1], row["imm"][2]))

    if "full" in verdict and "matched" in verdict:
        sf = verdict["full"]["ahead"][2]
        sm = verdict["matched"]["ahead"][2]
        agree = (sf > 0) == (sm > 0)
        print("  sign agreement full vs size-matched (ahead): %s" % ("YES" if agree else "*** NO"))
        if not agree:
            print("     ^ per PREREG this is INCONCLUSIVE, not negative: the dataset swap is")
            print("       doing the work rather than the features.")
        d = verdict["matched"]["ahead"][2]
        if d > 0 and 0.0005 <= d <= 0.004:
            print("  ahead gain %+.6f is INSIDE the predicted [0.0005, 0.004]" % d)
        elif d > 0.0002:
            print("  ahead gain %+.6f is positive but OUTSIDE the predicted band" % d)
        else:
            print("  ahead gain %+.6f FAILS P1 (needed > 0.0002)" % d)

        print()
        print("  FEATURES-ONLY figure (adding back the end-to-start penalty featB pays):")
        print("    ahead %+.6f   imm %+.6f"
              % (verdict["matched"]["ahead"][2] + IV_AHEAD,
                 verdict["matched"]["imm"][2] + IV_IMM))
        print("    ^ approximate: the interval cost was measured KD-ON at 558k on published dbs.")

    # ---------- P2: mechanism, on the interval-ADJUSTED delta ----------
    print()
    print("--- P2: the ADJUSTED gain rises with a user's same-day share")
    if not os.path.exists(SHARE_CACHE):
        print("  same-day cache missing (%s); run interval_verdict.py --shares" % SHARE_CACHE)
        return 0
    share = {int(k): v for k, v in json.load(open(SHARE_CACHE)).items()}

    iv = {}
    for mode in ("ahead", "imm"):
        a, b = load(IV_CTRL, mode), load(IV_TREAT, mode)
        iv[mode] = (a, b)
    have_iv = all(x is not None for m in iv for x in iv[m])
    if not have_iv:
        print("  interval pair jsonls missing -- cannot subtract the interval penalty.")
        return 0

    for mode in ("ahead", "imm"):
        ivc, ivt = iv[mode]
        users = [u for u in common if u in share and u in ivc and u in ivt]
        if len(users) < 100:
            print("  %s: only %d usable users, skipping" % (mode, len(users)))
            continue
        # featB gain, then add back this user's own measured interval penalty
        adj = {}
        for u in users:
            raw = data[(CTRL, mode)][u]["metrics"]["LogLoss"] - data[(TREAT, mode)][u]["metrics"]["LogLoss"]
            penalty = ivt[u]["metrics"]["LogLoss"] - ivc[u]["metrics"]["LogLoss"]
            adj[u] = raw + penalty
        qs = quartiles(users, share, adj)
        print("  %s (n=%d)  quartiles by same-day share, ADJUSTED gain:" % (mode, len(users)))
        for i, q in enumerate(qs):
            print("     Q%d  mean share %.4f   mean adjusted gain %+.6f"
                  % (i + 1, mean([share[u] for u in q]), mean([adj[u] for u in q])))
        lo, hi = mean([adj[u] for u in qs[0]]), mean([adj[u] for u in qs[3]])
        rho = spearman([share[u] for u in users], [adj[u] for u in users])
        print("     top/bottom ratio %s   Spearman rho %+.4f"
              % (("%.2fx" % (hi / lo)) if lo > 0 else "n/a (bottom <= 0)", rho))
        ok = (rho > 0.05) and (lo <= 0 or hi >= 2 * lo)
        print("     -> %s" % ("concentrated as predicted" if ok
                              else "NOT concentrated: the gain is not from the fine-grained timing columns"))

    print()
    print("REMINDER (PREREG): this is not a champion candidate -- gate #1 fails by construction.")
    print("Adoption re-bases on GENERATION 4, which fixes Bug C; gen 3 loses 37.2% of note")
    print("identity on cards with missing metadata. featB is directional, not the production number.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
